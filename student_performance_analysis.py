import pandas as pd
import matplotlib.pyplot as plt

# Create a sample dataset
data = {
    "Student": ["A", "B", "C", "D", "E", "F", "G", "H"],
    "Study_Hours": [1, 2, 3, 4, 5, 6, 7, 8],
    "Scores": [45, 50, 60, 65, 72, 80, 85, 95]
}

df = pd.DataFrame(data)

# 1. Inspect the dataset
print("FIRST FIVE ROWS")
print(df.head())

print("\nDATASET INFORMATION")
print(df.info())

# 2. Check for missing values
print("\nMISSING VALUES")
print(df.isnull().sum())

# 3. Calculate descriptive statistics
print("\nSUMMARY STATISTICS")
print(df[["Study_Hours", "Scores"]].describe())

# 4. Calculate correlation
correlation = df["Study_Hours"].corr(df["Scores"])
print("\nCORRELATION:", round(correlation, 3))

# 5. Visualize the relationship
plt.figure(figsize=(8, 5))
plt.scatter(df["Study_Hours"], df["Scores"])
plt.xlabel("Study Hours")
plt.ylabel("Scores")
plt.title("Study Hours vs Student Scores")
plt.grid(True)
plt.show()